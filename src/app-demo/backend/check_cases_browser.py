"""Run on a dedicated empty demo DB; creates three fictional cases and one quote."""
import os
import re
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path=os.environ['PLAYWRIGHT_CHROMIUM_EXECUTABLE'])
    page = browser.new_page(viewport={'width': 1440, 'height': 1080})
    page.set_default_timeout(5000)
    errors = []
    research = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: research.append(r.url) if '/price-research' in r.url else None)
    page.goto(os.environ.get('REPAIR_BASE_URL', 'http://127.0.0.1:5177'))
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading', name='見積もり案件', exact=True)).to_be_visible()
    for title, status, amount, due, car in [
        ('シビック オイル・バッテリー交換', 'unestimated', '19800', '2026-10-20', 'ホンダ シビック / FL4'),
        ('ジムニー ブレーキ交換', 'estimating', '35000', '2026-10-05', 'スズキ ジムニー / JB64W'),
        ('アクア オイル交換', 'completed', '8800', '', 'トヨタ アクア / NHP10'),
    ]:
        page.get_by_role('button', name='＋ 新規案件', exact=True).click()
        page.get_by_label('案件名', exact=True).fill(title)
        page.get_by_label('車両メモ', exact=True).fill(car)
        page.get_by_label('ステータス', exact=True).select_option(status)
        page.get_by_label('予定金額（税込・円）', exact=True).fill(amount)
        page.get_by_label('納期', exact=True).fill(due)
        page.get_by_role('button', name='案件を登録', exact=True).click()
        expect(page.locator('.case-table tbody')).to_contain_text(title)
    rows = page.locator('.case-table tbody tr')
    expect(rows).to_have_count(3)
    ids = rows.locator('.case-id').all_text_contents()
    assert len(set(ids)) == 3 and all(x.startswith('CASE-') for x in ids)
    expect(page.locator('.case-overdue')).to_have_count(1)
    page.screenshot(path='/tmp/estimate-cases-desktop.png', full_page=True)
    page.get_by_role('button', name=re.compile(r'^未見積もり')).click()
    expect(rows).to_have_count(1)
    page.get_by_role('button', name=re.compile(r'^すべて')).click()
    page.get_by_label('案件を検索', exact=True).fill('FL4')
    expect(rows).to_have_count(1)
    page.get_by_label('シビック オイル・バッテリー交換を編集', exact=True).click()
    page.get_by_label('予定金額（税込・円）', exact=True).fill('22000')
    page.get_by_label('納期', exact=True).fill('2026-10-25')
    page.get_by_label('案件メモ', exact=True).fill('部品の入荷待ち')
    page.get_by_role('button', name='変更を保存', exact=True).click()
    expect(rows).to_contain_text('￥22,000')
    expect(rows).to_contain_text('2026/10/25')
    page.get_by_label('案件を検索', exact=True).fill('')
    page.get_by_label('並び順', exact=True).select_option('due')
    expect(rows.first).to_contain_text('ジムニー')
    page.get_by_label('案件を検索', exact=True).fill(ids[2])
    expect(rows).to_have_count(1)
    page.get_by_label('案件を検索', exact=True).fill('FL4')
    case_id = rows.locator('.case-id').inner_text()
    page.get_by_role('button', name='見積もりを作成', exact=True).click()
    expect(page.locator('.case-editor-bar')).to_contain_text(case_id)
    page.get_by_label('登録済み車両を検索（外部通信なし）', exact=True).fill('FL4')
    page.locator('.vehicle-result').click()
    page.get_by_label('年式', exact=True).select_option('2022')
    page.get_by_label('グレード・仕様', exact=True).select_option(label='e:HEV（デモ仕様）')
    page.get_by_role('button', name='売上・利益', exact=True).click()
    expect(page.get_by_role('heading', name='働いた成果を、ひと目で。', exact=True)).to_be_visible()
    page.get_by_role('button', name='見積もり', exact=True).click()
    page.get_by_label('案件を検索', exact=True).fill('FL4')
    expect(rows.locator('.case-status')).to_have_text('見積もり中')
    page.get_by_role('button', name='見積もりを作成', exact=True).click()
    expect(page.get_by_label('年式', exact=True)).to_have_value('2022')
    page.get_by_role('button', name='作業を選ぶ', exact=True).click()
    page.get_by_label('エンジンオイル交換').check()
    page.get_by_label('補機バッテリー交換').check()
    page.get_by_role('button', name='参考価格を比較する', exact=True).click()
    page.get_by_role('button', name='金額を確認する', exact=True).click()
    page.get_by_role('button', name='金額を確定して保存', exact=True).click()
    expect(page.get_by_role('heading', name='見積もりを保存しました', exact=True)).to_be_visible()
    saved_total = page.locator('.saved-total').inner_text()
    page.get_by_role('button', name='案件一覧で確認する', exact=True).click()
    expect(rows.locator('.case-status')).to_have_text('完了')
    expect(rows).to_contain_text(saved_total)
    expect(rows).to_contain_text('2026/10/25')
    expect(rows).to_contain_text('部品の入荷待ち')
    assert rows.locator('.case-id').inner_text() == case_id
    page.reload()
    page.wait_for_load_state('networkidle')
    page.get_by_label('案件を検索', exact=True).fill(case_id)
    expect(rows).to_have_count(1)
    page.get_by_role('button', name='見積もりを開く', exact=True).click()
    expect(page.get_by_role('heading', name='金額を確定・保存', exact=True)).to_be_visible()
    expect(page.get_by_label('年式', exact=True)).to_have_count(0)
    expect(page.locator('.summary-total strong')).to_have_text(saved_total)
    page.get_by_role('button', name='案件一覧に戻る', exact=True).click()
    page.get_by_label('案件を検索', exact=True).fill('')
    page.screenshot(path='/tmp/estimate-cases-completed.png', full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path='/tmp/estimate-cases-mobile.png', full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.get_by_label('アクア オイル交換を編集', exact=True).click()
    page.screenshot(path='/tmp/estimate-cases-mobile-form.png', full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    assert len(research) == 1
    assert not errors, errors
    browser.close()
    print('PASS: unique IDs, status filters, ID/vehicle search, edit, due sorting, overdue, draft continuity, quote linkage/completion, reload, mobile, no browser errors')

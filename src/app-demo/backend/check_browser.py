"""Run against a dedicated running demo backend/frontend; writes one estimate."""
import os
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path=os.environ.get('PLAYWRIGHT_CHROMIUM_EXECUTABLE') or None)
    page = browser.new_page(viewport={'width': 1440, 'height': 1080})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:5177')
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading', name='車両を選ぶ', exact=True)).to_be_visible()
    page.screenshot(path='/tmp/repair-demo-desktop.png', full_page=True)
    page.get_by_label('車種名・型式', exact=True).fill('シビック')
    expect(page.locator('.vehicle-result')).to_have_count(2)
    page.get_by_label('車種名・型式', exact=True).fill('FL4')
    expect(page.locator('.vehicle-result')).to_have_count(1)
    page.locator('.vehicle-result').click()
    page.get_by_label('年式', exact=True).select_option('2023')
    page.get_by_label('グレード・仕様', exact=True).select_option(label='e:HEV（デモ仕様）')
    page.get_by_role('button', name='作業を選ぶ', exact=True).click()
    page.get_by_label('フロントブレーキパッド交換').check()
    page.get_by_role('button', name='参考価格を比較する').click()
    expect(page.locator('.source-card')).to_have_count(4)
    expect(page.locator('.median-strip strong')).to_have_text('￥6,000')
    page.locator('.source-card').nth(2).get_by_role('checkbox').uncheck()
    expect(page.locator('.median-strip strong')).to_have_text('￥5,500')
    page.locator('.source-card').nth(0).get_by_role('checkbox').uncheck()
    page.locator('.source-card').nth(1).get_by_role('checkbox').uncheck()
    expect(page.locator('.median-strip strong')).to_have_text('算出不可')
    page.get_by_role('button', name='金額を確認する').click()
    expect(page.get_by_role('button', name='金額を確定して保存')).to_be_disabled()
    page.get_by_label('フロントブレーキパッド交換の確定工賃').fill('7000')
    page.get_by_label('フロントブレーキパッド交換の部品代').fill('12000')
    page.get_by_label('工賃の手入力・調整理由').fill('ブラウザ検証：候補を全除外して手入力')
    expect(page.locator('.summary-total strong')).to_have_text('￥20,900')
    page.get_by_role('button', name='金額を確定して保存').click()
    expect(page.get_by_role('heading', name='見積もりを保存しました')).to_be_visible()
    page.reload()
    page.wait_for_load_state('networkidle')
    page.get_by_role('button', name='保存した見積もり', exact=True).click()
    page.get_by_label('見積もり履歴を検索').fill('FL4')
    expect(page.locator('.history-list > button').first).to_be_visible()
    page.locator('.history-list > button').first.click()
    expect(page.locator('.detail-total strong')).to_have_text('￥20,900')
    expect(page.locator('.history-detail')).to_contain_text('ブラウザ検証：候補を全除外して手入力')
    page.get_by_role('button', name='この条件で見積もりを作る').click()
    expect(page.get_by_role('heading', name='金額を確定・保存', exact=True)).to_be_visible()
    expect(page.get_by_label('フロントブレーキパッド交換の確定工賃')).to_have_value('7000')
    # Comparison: four sources, source metadata, and calculation must fit a narrow screen.
    page.get_by_role('button', name='候補比較へ戻る').click()
    page.screenshot(path='/tmp/repair-demo-comparison.png', full_page=True)
    page.set_viewport_size({'width': 390, 'height': 844})
    page.screenshot(path='/tmp/repair-demo-mobile.png', full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile horizontal overflow'
    page.get_by_role('button', name='保存した見積もり', exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).to_have_count(0)
    assert not errors, errors
    browser.close()
    print('PASS: search, explicit variant, comparison, zero candidates, manual adjustment, tax, SQLite persistence, history reuse, mobile overflow, Escape, no browser errors')
